rows = list(csv.DictReader(open(CSV, encoding="utf-8")))
sb = [r for r in rows if r["app"] != "NEW"]
b2b = [r for r in rows if r["app"] == "NEW"]

calcs = {c["id"]: c for c in REG["calculations"]}
gv_by_calc = defaultdict(list)
for v in GVS:
    gv_by_calc[v["calc"]].append(v["id"])
gv = {v["id"]: v for v in GVS}

# ---------------------------------------------------------------- integrity checks
def scope_of(r):
    s = (r.get("v03_scope") or "").strip()
    if s == "IN":
        return "IN"
    if s.startswith("OMITTED"):
        return "OMITTED"
    return None


errors = []
for r in rows:
    c = r["sow_calc_after"]
    sc = scope_of(r)
    if sc is None:
        errors.append(f"{r['audit_id']}: unknown v03_scope {r.get('v03_scope')!r}")
    if c not in calcs:
        errors.append(f"{r['audit_id']}: unknown calc {c}")
        continue
    if not gv_by_calc.get(c):
        errors.append(f"{r['audit_id']}: {c} has no golden vector")
    if sc == "IN" and calcs[c].get("scope") == "OMITTED":
        errors.append(f"{r['audit_id']}: IN row maps to OMITTED calc {c}")
if len({r["audit_id"] for r in rows}) != len(rows):
    errors.append("duplicate audit_id")
if errors:
    sys.exit("build_doc10: " + "; ".join(errors))

